using AppForSEII.API.Controllers;
using AppForSEII.API.DTOs.PurchaseDTOs;
using Microsoft.Extensions.Logging;
using Moq;

namespace AppForSEII.UT.CretePurchase_test.CreatePurchase_test;

public class CreatePurchase_test : IClassFixture<DatabaseFixture4GetOperations>
{
    // Must be the UserName of _fixture.Customer
    private const string _userName = "taylor@example.com";

    private readonly DatabaseFixture4GetOperations _fixture;

    public CreatePurchase_test(DatabaseFixture4GetOperations fixture)
    {
        _fixture = fixture;
    }

    public static IEnumerable<object[]> TestCasesFor_CreatePurchase()
    {
        var purchaseNoItems = CreateRequest(_userName);

        var purchaseDuplicatedItem = CreateRequest(
            _userName, new PurchaseItemDTO(1, 1), new PurchaseItemDTO(1, 2));

        var purchaseItemNotExisting = CreateRequest(
            _userName, new PurchaseItemDTO(int.MaxValue, 1));

        var purchaseUnknownUser = CreateRequest(
            "missing-user", new PurchaseItemDTO(1, 1));

        var purchaseBlankUser = CreateRequest(
            "   ", new PurchaseItemDTO(1, 1));

        var allTests = new List<object[]>
        {   // input for CreatePurchase - Error expected
            new object[] { purchaseNoItems, "Select at least one item." },
            new object[] { purchaseDuplicatedItem, "An item can only be selected once." },
            new object[] { purchaseItemNotExisting, "One or more selected items do not exist." },
            new object[] { purchaseUnknownUser, "The customer username was not found." },
            new object[] { purchaseBlankUser, "Customer username is required." },
        };

        return allTests;
    }

    [Theory]
    [Trait("LevelTesting", "Unit Testing")]
    [Trait("Database", "WithFixture")]
    [MemberData(nameof(TestCasesFor_CreatePurchase))]
    public async Task CreatePurchase_Error_test(PurchaseForCreateDTO purchaseDTO, string errorExpected)
    {
        // Arrange
        using var context = _fixture.CreateContext();
        var mock = new Mock<ILogger<PurchasesController>>();
        ILogger<PurchasesController> logger = mock.Object;

        var controller = new PurchasesController(context, logger);

        // Act
        var result = await controller.CreatePurchase(purchaseDTO);

        // Assert
        // we check that the response type is BadRequest and obtain the error returned
        var badRequestResult = Assert.IsType<BadRequestObjectResult>(result.Result);
        var problemDetails = Assert.IsType<ValidationProblemDetails>(badRequestResult.Value);

        var errorActual = problemDetails.Errors.First().Value[0];

        // we check that the expected error message and actual are the same
        Assert.StartsWith(errorExpected, errorActual);
    }

    [Fact]
    [Trait("LevelTesting", "Unit Testing")]
    [Trait("Database", "WithFixture")]
    public async Task CreatePurchase_NotEnoughStock_test()
    {
        // Arrange
        var stockBefore = await GetStock();
        using var context = _fixture.CreateContext();
        var mock = new Mock<ILogger<PurchasesController>>();
        ILogger<PurchasesController> logger = mock.Object;

        var controller = new PurchasesController(context, logger);
        var purchaseDTO = CreateRequest(
            _userName, new PurchaseItemDTO(_fixture.FootballBoots.Id, stockBefore + 1));

        // Act
        var result = await controller.CreatePurchase(purchaseDTO);

        // Assert
        // we check that the response type is Conflict and the stock has not changed
        var conflictResult = Assert.IsType<ConflictObjectResult>(result.Result);
        var message = Assert.IsType<string>(conflictResult.Value);
        Assert.StartsWith("There is not enough stock for Football Boots", message);
        Assert.Equal(stockBefore, await GetStock());
    }

    [Fact]
    [Trait("LevelTesting", "Unit Testing")]
    [Trait("Database", "WithFixture")]
    public async Task CreatePurchase_Success_test()
    {
        // Arrange
        var stockBefore = await GetStock();
        using var context = _fixture.CreateContext();
        var mock = new Mock<ILogger<PurchasesController>>();
        ILogger<PurchasesController> logger = mock.Object;

        var controller = new PurchasesController(context, logger);
        var purchaseDTO = CreateRequest(
            _userName, new PurchaseItemDTO(_fixture.FootballBoots.Id, 2));

        // Act
        var result = await controller.CreatePurchase(purchaseDTO);

        // Assert
        // we check that the response type is CreatedAtAction and obtain the purchase
        var createdResult = Assert.IsType<CreatedAtActionResult>(result.Result);
        var actualPurchaseDetailDTO = Assert.IsType<PurchaseDetailDTO>(createdResult.Value);

        // Id and date are generated by the controller/database,
        // so the expected DTO takes them from the actual one
        var expectedPurchaseDetailDTO = new PurchaseDetailDTO(
            actualPurchaseDetailDTO.Id,
            actualPurchaseDetailDTO.PurchaseDate,
            "Purchase test",
            119.80m,
            true,
            new PurchaseUserDTO("Taylor", "Smith"),
            new List<PurchaseItemDTO>
            {
                new(
                    _fixture.FootballBoots.Id,
                    "Football Boots",
                    "Nike",
                    59.90m,
                    21,
                    Gender.Male,
                    "42",
                    "Football",
                    2)
            },
            _userName);

        Assert.Equal(expectedPurchaseDetailDTO, actualPurchaseDetailDTO);

        // the Location header must point to GetPurchase with the new id
        Assert.Equal(nameof(PurchasesController.GetPurchase), createdResult.ActionName);
        Assert.Equal(actualPurchaseDetailDTO.Id, Assert.IsType<int>(createdResult.RouteValues!["id"]));

        // stock reduced and purchase really saved
        Assert.Equal(stockBefore - 2, await GetStock());

        using var verificationContext = _fixture.CreateContext();
        var persistedPurchase = await verificationContext.Purchases
            .Include(savedPurchase => savedPurchase.PurchaseItems)
            .SingleAsync(savedPurchase => savedPurchase.Id == actualPurchaseDetailDTO.Id);
        Assert.Equal(_fixture.Customer.Id, persistedPurchase.UserId);
        Assert.Equal(PurchaseStatus.Created, persistedPurchase.PurchaseStatus);
        Assert.Equal(119.80m, persistedPurchase.TotalPrice);
        var persistedItem = Assert.Single(persistedPurchase.PurchaseItems);
        Assert.Equal(2, persistedItem.Quantity);
    }

    [Fact]
    [Trait("LevelTesting", "Unit Testing")]
    [Trait("Database", "WithFixture")]
    public async Task CreatePurchase_SaveFailure_test()
    {
        // Arrange
        var stockBefore = await GetStock();
        using (var context = _fixture.CreateContext())
        {
            await context.Database.ExecuteSqlRawAsync(
                "CREATE TRIGGER \"FailPurchaseInsert\" BEFORE INSERT ON \"Purchases\" " +
                "BEGIN SELECT RAISE(ABORT, 'Simulated insert failure'); END;");
        }

        using var purchaseContext = _fixture.CreateContext();
        var mock = new Mock<ILogger<PurchasesController>>();
        ILogger<PurchasesController> logger = mock.Object;

        var controller = new PurchasesController(purchaseContext, logger);
        var purchaseDTO = CreateRequest(
            _userName, new PurchaseItemDTO(_fixture.FootballBoots.Id, 1));

        try
        {
            // Act
            var result = await controller.CreatePurchase(purchaseDTO);

            // Assert
            Assert.IsType<ConflictObjectResult>(result.Result);
            Assert.Equal(stockBefore, await GetStock());
        }
        finally
        {
            using var context = _fixture.CreateContext();
            await context.Database.ExecuteSqlRawAsync(
                "DROP TRIGGER IF EXISTS \"FailPurchaseInsert\";");
        }
    }

    private static PurchaseForCreateDTO CreateRequest(
        string customerUserName,
        params PurchaseItemDTO[] items)
    {
        return new PurchaseForCreateDTO(
            "Main Street 1",
            "Barcelona",
            "Barcelona",
            "4111111111111111",
            "123",
            "12/30",
            "Purchase test",
            true,
            items.ToList(),
            customerUserName);
    }

    private async Task<int> GetStock()
    {
        using var context = _fixture.CreateContext();
        return await context.Items
            .Where(item => item.Id == _fixture.FootballBoots.Id)
            .Select(item => item.QuantityAvailableForPurchase)
            .SingleAsync();
    }
}